#!/bin/bash
# The Airflow prototype in separate containers (docker-compose.yaml next to this file), driven like
# ../../airflow_demo/airflow_demo.sh drives it on the bare host: same commands, same scenarios.
# Docker Compose does the process management: this script only adds the per-checkout naming and
# secrets, and forwards everything about the demo itself to airflow_demo.sh inside a one-shot
# container, where it finds the same volumes and database as the services.
#
# Needs Docker with Compose v2 -- no Airflow venv, no Postgres and no tmux on the host.
#
# Quick start:
#   ./airflow_automation/airflow_containers/compose/airflow_compose.sh play scenario-player/scenarios/basic_ecal_pedestals.yaml
#   ./airflow_automation/airflow_containers/compose/airflow_compose.sh ui
#   ./airflow_automation/airflow_containers/compose/airflow_compose.sh down

set -euo pipefail

COMPOSE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# For the per-checkout names and overrides (NGT_INSTANCE, NGT_AIRFLOW_PORT, local_*_env.sh). Its other
# settings describe the bare-host instance: docker-compose.yaml reads none of them.
# shellcheck disable=SC1091
source "$COMPOSE_DIR/../../airflow_demo/airflow_env.sh"

# Beside the same checkout's bare-host instance, which keeps NGT_AIRFLOW_PORT itself.
export NGT_COMPOSE_PORT="${NGT_COMPOSE_PORT:-$((NGT_AIRFLOW_PORT + 3000))}"
export COMPOSE_PROJECT_NAME="${COMPOSE_PROJECT_NAME:-ngt_airflow_$NGT_INSTANCE}"
export NGT_AIRFLOW_IMAGE="${NGT_AIRFLOW_IMAGE:-ngt-airflow:$NGT_INSTANCE}"
# What docker-compose.yaml reads, also when only local_airflow_env.sh sets it. Unset stays unset.
export NGT_AIRFLOW_ALL_ADMINS NGT_AIRFLOW_USERS NGT_CONTAINER_UID NGT_POSTGRES_IMAGE NGT_AIRFLOW_BASE_IMAGE
export NGT_RUN_END_GRACE_SECONDS

SERVICES=(airflow-api-server airflow-scheduler airflow-dag-processor airflow-triggerer)
ENV_FILE="${NGT_COMPOSE_ENV_FILE:-$COMPOSE_DIR/.env}"

usage() {
  cat <<USAGE
Usage: $0 <command> [args]

Running Airflow (project $COMPOSE_PROJECT_NAME -- UI on 127.0.0.1:$NGT_COMPOSE_PORT):
  build                       (Re)build the image from this checkout. Needed after changing the code.
  start                       Build the image if it's missing, start everything, wait until it's healthy
  stop                        Stop the containers, keeping all state in their volumes
  down                        Remove the containers AND the volumes: DAG history, data, everything
  status                      The containers and their health
  ui                          Print the Airflow UI URL
  logins                      With NGT_AIRFLOW_ALL_ADMINS=False, the generated UI logins
  logs <component>            Follow a log: api-server, scheduler, dag-processor, triggerer, postgres
  shell                       A shell among the services' volumes and database

Resetting state (see airflow_demo.sh's usage):
  reset-scenario              Wipe the scratch data + the watchers' watermarks, restarting the services around it
  reset-airflow               Wipe the metadata DB, restarting the services around it
  reset-watch                 Clear the 4 DAGs' history and Assets, which also pauses them again

Everything else is passed to airflow_demo.sh inside a one-shot container -- run that with no
arguments for the details: unpause-watch, pause-watch, seed-run, add-ls, end-run, list-runs,
play, arm-fault, list-faults, clear-faults. \`play\` starts everything first, as it does there, and
takes a scenario path on this host.
USAGE
}

ensure_env_file() {
  # Secrets generated once per checkout, in a gitignored file. Fixed rather than per-start: the
  # Fernet key decrypts what's stored in the database volume.
  [ -f "$ENV_FILE" ] && return
  (
    umask 077
    python3 - > "$ENV_FILE" <<'PY'
import base64
import os
import secrets

print("# Generated by airflow_compose.sh -- see docker-compose.yaml. Gitignored.")
print(f"NGT_POSTGRES_PASSWORD={secrets.token_hex(16)}")
print(f"NGT_JWT_SECRET={secrets.token_hex(32)}")
print(f"NGT_API_SECRET_KEY={secrets.token_hex(32)}")
print(f"NGT_FERNET_KEY={base64.urlsafe_b64encode(os.urandom(32)).decode()}")
PY
  )
}

compose() {
  ensure_env_file
  docker compose --project-directory "$COMPOSE_DIR" -f "$COMPOSE_DIR/docker-compose.yaml" --env-file "$ENV_FILE" "$@"
}

in_tools() {
  # $@: a command in a one-shot tools container. A TTY only if we have one -- `play --interactive` needs it.
  local options=(--rm)
  if ! { [ -t 0 ] && [ -t 1 ]; }; then options+=(-T); fi
  compose --profile tools run "${options[@]}" "${TOOLS_MOUNTS[@]+"${TOOLS_MOUNTS[@]}"}" tools "$@"
}

demo_in_tools() {
  # $@: an airflow_demo.sh command. Through bash because the image's entrypoint hands everything else to `airflow`.
  in_tools bash -c 'exec airflow_demo.sh "$@"' airflow_demo.sh "$@"
}

any_running() {
  [ -n "$(compose ps -q --status running "${SERVICES[@]}")" ]
}

cmd_start() {
  if [ -z "$(docker images -q "$NGT_AIRFLOW_IMAGE")" ]; then
    compose build airflow-init
  fi
  compose up -d --wait "${SERVICES[@]}"
  cmd_ui
}

cmd_ui() {
  echo "Airflow UI: http://localhost:$NGT_COMPOSE_PORT"
}

cmd_logs() {
  local which="${1:?api-server, scheduler, dag-processor, triggerer or postgres required}"
  case "$which" in
    postgres) compose logs -f postgres ;;
    api-server|scheduler|dag-processor|triggerer) compose logs -f "airflow-$which" ;;
    *) echo "Usage: $0 logs <api-server|scheduler|dag-processor|triggerer|postgres>" >&2; exit 1 ;;
  esac
}

cmd_logins() {
  compose exec -T airflow-api-server cat /opt/airflow/simple_auth_manager_passwords.json.generated || {
    echo "No generated logins: they only exist with NGT_AIRFLOW_ALL_ADMINS=False set at '$0 start'." >&2
    exit 1
  }
}

reset_with_services_stopped() {
  # As airflow_demo.sh's own reset-* do around their tmux sessions: running components hold state
  # tied to what's being wiped.
  local was_running=0
  if any_running; then
    was_running=1
    compose stop "${SERVICES[@]}"
  fi
  demo_in_tools "$@"
  if [ "$was_running" = 1 ]; then
    compose up -d --wait "${SERVICES[@]}"
  fi
}

cmd_play() {
  # Scenario files are on this host, the player in a container: each argument naming a file is
  # mounted, wherever it is, so an edited or new scenario needs no image rebuild.
  local arg file args=()
  TOOLS_MOUNTS=()
  for arg in "$@"; do
    if [ -f "$arg" ]; then
      file="$(cd "$(dirname "$arg")" && pwd)/$(basename "$arg")"
      TOOLS_MOUNTS+=(-v "$file:/tmp/scenarios/$(basename "$arg"):ro")
      arg="/tmp/scenarios/$(basename "$arg")"
    fi
    args+=("$arg")
  done
  cmd_start
  demo_in_tools play "${args[@]}"
}

TOOLS_MOUNTS=()

case "${1:-}" in
  build) compose build airflow-init ;;
  start) cmd_start ;;
  stop) compose stop ;;
  down) compose --profile tools down --volumes --remove-orphans ;;
  status) compose ps -a ;;
  ui) cmd_ui ;;
  logins) cmd_logins ;;
  logs) cmd_logs "${2:-}" ;;
  shell) in_tools bash ;;
  reset-scenario|reset-airflow) reset_with_services_stopped "$1" ;;
  play) shift; cmd_play "$@" ;;
  unpause-watch|pause-watch|reset-watch|seed-run|add-ls|end-run|list-runs|arm-fault|list-faults|clear-faults)
    demo_in_tools "$@"
    ;;
  *) usage; exit 1 ;;
esac
